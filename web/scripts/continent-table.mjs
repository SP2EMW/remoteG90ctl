// Builds web/src/continents-data.ts: the continent of each state in the ITU
// table (countries-data.ts) and the outlines of the states by continent, from
// Natural Earth's 1:110m countries (public domain, ne_110m_admin_0_countries
// of nvkelso/natural-earth-vector v5.1.2), for "spots near this station"
// (owner's request 2026-11-28). Russia is tagged RU: Europe west of 60 E,
// Asia east of it. States the 110m file lacks or names otherwise are listed
// below by hand (geography). Run by hand:
//
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson
//   node web/scripts/continent-table.mjs ne_110m_admin_0_countries.geojson

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const CODES = {
  Europe: "EU",
  Asia: "AS",
  Africa: "AF",
  "North America": "NA",
  "South America": "SA",
  Oceania: "OC",
  Antarctica: "AN",
};
// ITU names the 110m file lacks or names otherwise; organisations have none.
const BY_HAND = {
  Andorra: "EU", "Antigua and Barbuda": "NA", Bahrain: "AS", Barbados: "NA", "Cabo Verde": "AF",
  "China - Hong Kong": "AS", "China - Macao": "AS", Comoros: "AF", Dominica: "NA", Grenada: "NA",
  Kiribati: "OC", Korea: "AS", Maldives: "AS", Malta: "EU", "Marshall Islands": "OC", Mauritius: "AF",
  Micronesia: "OC", Monaco: "EU", "Netherlands - Aruba": "SA", "New Zealand - Cook Islands": "OC",
  "New Zealand - Niue": "OC", Palau: "OC", "Republic of Naoero": "OC", "Republic of Türkiye": "AS",
  "Saint Kitts and Nevis": "NA", "Saint Lucia": "NA", "Saint Vincent and the Grenadines": "NA", Samoa: "OC",
  "San Marino": "EU", "Sao Tome and Principe": "AF", Seychelles: "AF", Singapore: "AS", "State of Palestine": "AS",
  Tonga: "OC", Tuvalu: "OC", "Vatican City State": "EU", "Viet Nam": "AS",
};
const NONE = new Set(["International Civil Aviation Organization", "United Nations", "World Meteorological Organization"]);

const [file] = process.argv.slice(2);
if (!file) {
  console.error("usage: node continent-table.mjs ne_110m_admin_0_countries.geojson");
  process.exit(2);
}
const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const geo = JSON.parse(readFileSync(file, "utf8"));
const names = JSON.parse(/COUNTRY_NAMES[^=]*= (\[.*?\]);/s.exec(readFileSync(join(web, "src", "countries-data.ts"), "utf8"))[1]);

const byName = new Map();
const rings = [];
for (const feature of geo.features) {
  const p = feature.properties;
  const code = CODES[p.CONTINENT];
  if (code === undefined) continue; // open ocean
  for (const key of ["ADMIN", "NAME", "NAME_LONG", "FORMAL_EN", "SOVEREIGNT", "NAME_EN"]) {
    if (p[key]) byName.set(String(p[key]).toLowerCase(), code);
  }
  const tag = p.ADMIN === "Russia" ? "RU" : code;
  const g = feature.geometry;
  for (const polygon of g.type === "Polygon" ? [g.coordinates] : g.coordinates) {
    const ring = [];
    for (const [lon, lat] of polygon[0]) {
      const pt = [Math.round(lon * 10), Math.round(lat * 10)];
      const last = ring[ring.length - 1];
      // Points under half a degree from the last are dropped: enough to tell continents.
      if (last === undefined || Math.abs(last[0] - pt[0]) + Math.abs(last[1] - pt[1]) >= 5) ring.push(pt);
    }
    if (ring.length >= 3) rings.push(`${tag}:${ring.flat().join(",")}`);
  }
}
const ofCountry = {};
for (const name of names) {
  if (NONE.has(name)) continue;
  const code = BY_HAND[name] ?? byName.get(name.toLowerCase());
  if (code === undefined) throw new Error(`no continent for ${name}`);
  ofCountry[name] = code;
}
const out = `// SPDX-License-Identifier: GPL-3.0-or-later
//
// Generated by web/scripts/continent-table.mjs; do not edit. Continents of
// the ITU table's states and the states' outlines (tagged by continent; RU:
// Russia, Europe west of 60 E, Asia east of it), longitude and latitude in
// tenths of a degree, from Natural Earth 1:110m countries (public domain).
// See docs/third-party.md.

export const CONTINENT_OF_COUNTRY: Readonly<Record<string, string>> = ${JSON.stringify(ofCountry)};

export const CONTINENT_RINGS: readonly string[] = ${JSON.stringify(rings)};
`;
writeFileSync(join(web, "src", "continents-data.ts"), out);
console.log(`${Object.keys(ofCountry).length} states, ${rings.length} rings, ${out.length} bytes`);
