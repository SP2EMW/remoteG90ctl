// Builds web/src/land-data.ts, the land outlines of the Propagation window's
// map, from Natural Earth's 1:110m land polygons (public domain,
// https://www.naturalearthdata.com/, file ne_110m_land.geojson of
// nvkelso/natural-earth-vector v5.1.2). Coordinates in tenths of a degree;
// points closer than a tenth to the previous one are dropped. Run by hand:
//
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
//   node web/scripts/land-table.mjs ne_110m_land.geojson

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [file] = process.argv.slice(2);
if (!file) {
  console.error("usage: node land-table.mjs ne_110m_land.geojson");
  process.exit(2);
}
const geo = JSON.parse(readFileSync(file, "utf8"));
const rings = [];
for (const feature of geo.features) {
  const g = feature.geometry;
  const polygons = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const polygon of polygons) {
    const ring = [];
    for (const [lon, lat] of polygon[0]) {
      const p = [Math.round(lon * 10), Math.round(lat * 10)];
      const last = ring[ring.length - 1];
      if (last === undefined || last[0] !== p[0] || last[1] !== p[1]) ring.push(p);
    }
    if (ring.length >= 4) rings.push(ring.flat().join(","));
  }
}
const out = `// SPDX-License-Identifier: GPL-3.0-or-later
//
// Generated by web/scripts/land-table.mjs; do not edit. Land outlines from
// Natural Earth 1:110m (public domain), longitude and latitude in tenths of a
// degree, one ring per entry. See docs/third-party.md.

export const LAND_RINGS: readonly string[] = ${JSON.stringify(rings)};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "land-data.ts"), out);
console.log(`${rings.length} rings, ${rings.reduce((n, r) => n + r.split(",").length / 2, 0)} points, ${out.length} bytes`);
