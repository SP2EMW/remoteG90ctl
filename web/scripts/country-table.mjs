// Builds web/src/countries-data.ts from the ITU's Table of allocation of
// international call sign series (Radio Regulations, Appendix 42), as the ITU
// publishes it at https://www.itu.int/gladapp/Allocation/CallSigns (linked
// from https://www.itu.int/en/ITU-R/terrestrial/fmd/Pages/call_sign_series.aspx).
// Facts, not code; see docs/third-party.md. Run by hand when the ITU changes
// the table, with the page saved first:
//
//   curl -o callsigns.html https://www.itu.int/gladapp/Allocation/CallSigns
//   node web/scripts/country-table.mjs callsigns.html 2026-11-27
//
// (the second argument: the date the page was read).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [page, read] = process.argv.slice(2);
if (!page || !/^\d{4}-\d{2}-\d{2}$/.test(read ?? "")) {
  console.error("usage: node country-table.mjs CALLSIGNS.html YYYY-MM-DD");
  process.exit(2);
}
const decode = (s) =>
  s.replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n))).replace(/&amp;/g, "&").replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"');
const html = readFileSync(page, "utf8");
const rows = [];
for (const [, row] of html.matchAll(/<tr>([\s\S]*?)<\/tr>/g)) {
  const series = [...row.matchAll(/class="button-style"[^>]*>\s*([^<]+?)\s*<\/span>/g)].map((m) => m[1]);
  const cells = [...row.matchAll(/<td>\s*([^<]+?)\s*<\/td>/g)].map((m) => decode(m[1]));
  if (series.length === 0 || cells.length === 0) continue;
  // "Poland (Republic of)" -> "Poland": the name without the form of state.
  const name = cells[cells.length - 1].replace(/\s*\([^)]*\)/g, "").replace(/\s+/g, " ").trim();
  for (const s of series) {
    const m = /^([A-Z0-9]{2})([A-Z]) - ([A-Z0-9]{2})([A-Z])$/.exec(s);
    if (m === null || m[1] !== m[3]) throw new Error(`unexpected series ${s}`);
    rows.push([m[1], m[2], m[4], name]);
  }
}
if (rows.length < 900) throw new Error(`only ${rows.length} series read`);
// A series listed for several parts of one state (PJ: three parts of the
// Kingdom of the Netherlands) goes to their common name; with none, it is left
// out (no guess).
for (let i = 0; i < rows.length; i++) {
  const same = rows.filter((r) => r[0] === rows[i][0] && r[1] === rows[i][1] && r[2] === rows[i][2]);
  if (same.length < 2) continue;
  const bases = new Set(same.map((r) => r[3].split(" - ")[0]));
  const common = bases.size === 1 ? [...bases][0] : null;
  for (let j = rows.length - 1; j >= 0; j--) if (same.includes(rows[j])) rows.splice(j, 1);
  if (common !== null) rows.splice(i, 0, [same[0][0], same[0][1], same[0][2], common]);
  i--;
}
const names = [...new Set(rows.map((r) => r[3]))].sort();
// "SP:123" for a whole two-character series, "3DA-3DM:45" for part of one.
const entries = rows.map(([key, from, to, name]) =>
  from === "A" && to === "Z" ? `${key}:${names.indexOf(name)}` : `${key}${from}-${key}${to}:${names.indexOf(name)}`,
);
const out = `// SPDX-License-Identifier: GPL-3.0-or-later
//
// Generated by web/scripts/country-table.mjs; do not edit. Data: the ITU's
// Table of allocation of international call sign series (Radio Regulations,
// Appendix 42), https://www.itu.int/gladapp/Allocation/CallSigns, read ${read};
// ${rows.length} series. See docs/third-party.md.

export const COUNTRY_NAMES: readonly string[] = ${JSON.stringify(names, null, 0)};

export const CALL_SERIES = "${entries.join(" ")}";
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "countries-data.ts"), out);
console.log(`${rows.length} series, ${names.length} names`);
